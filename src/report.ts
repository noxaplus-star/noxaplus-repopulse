export function renderMarkdownReport(result: AuditResult): string {
  const rows = result.checks.map(check => `| ${STATUS_LABEL[check.status]} | ${check.title} | ${check.categoryTitle} | ${check.earned} / ${check.weight} | ${check.detail.replaceAll('|', '\\|')} |`);
  return `# RepoPulse report: ${result.repo.fullName}

**Score:** ${result.score} / 100 (${result.grade})  
**Verdict:** ${result.summary}  
**Generated:** ${result.generatedAt}  
**Repository:** ${result.repo.htmlUrl}

## Categories

| Category | Points | Percent |
| --- | ---: | ---: |
${result.categories.map(category => `| ${category.title} | ${category.earned} / ${category.weight} | ${category.percent}% |`).join('\n')}

## Do these next

${result.priorityFixes.map((check, index) => `${index + 1}. **${check.title}** — ${check.fix}`).join('\n') || 'Nothing urgent.'}

## All checks

| Status | Check | Category | Points | Detail |
| --- | --- | --- | ---: | --- |
${rows.join('\n')}

---

Generated locally by [NoxaPlus RepoPulse](https://github.com/noxaplus-star/noxaplus-repopulse). MIT licensed.
`;
}

export function renderBadge(result: Pick<AuditResult, 'score' | 'grade'>): string {
  const color = scoreColor(result.score);
  const label = 'RepoPulse';
  const value = `${result.score} ${result.grade}`;
  const labelWidth = 96;
  const valueWidth = 74;
  const total = labelWidth + valueWidth;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${total}" height="28" viewBox="0 0 ${total} 28" role="img" aria-label="RepoPulse health score: ${value}">
  <title>RepoPulse: ${value}</title>
  <linearGradient id="s" x2="0" y2="100%"><stop offset="0" stop-color="#fff" stop-opacity=".18"/><stop offset="1" stop-opacity=".08"/></linearGradient>
  <clipPath id="r"><rect width="${total}" height="28" rx="6"/></clipPath>
  <g clip-path="url(#r)">
    <rect width="${labelWidth}" height="28" fill="#0b1220"/>
    <rect x="${labelWidth}" width="${valueWidth}" height="28" fill="${color}"/>
    <rect width="${total}" height="28" fill="url(#s)"/>
  </g>
  <g fill="#fff" font-family="Verdana,DejaVu Sans,sans-serif" font-size="11" text-anchor="middle">
    <text x="${labelWidth / 2}" y="18" fill="#cbd5e1" font-weight="600">${label}</text>
    <text x="${labelWidth + valueWidth / 2}" y="18" fill="#071018" font-weight="700">${value}</text>
  </g>
</svg>`;
}

