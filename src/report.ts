import type { AuditResult, CheckResult, CheckStatus } from './types.js';

const STATUS_LABEL: Record<CheckStatus, string> = { pass: 'Pass', warn: 'Partial', fail: 'Missing' };

function escapeHtml(value: string): string {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

function formatDate(value: string | null): string {
  if (!value) return 'Unknown';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return 'Unknown';
  return date.toISOString().slice(0, 10);
}

function scoreColor(score: number): string {
  if (score >= 85) return '#34d399';
  if (score >= 70) return '#a3e635';
  if (score >= 55) return '#fbbf24';
  return '#f87171';
}

function gradeTone(score: number): string {
  if (score >= 85) return 'excellent';
  if (score >= 70) return 'good';
  if (score >= 55) return 'fair';
  return 'poor';
}

function statusCount(checks: CheckResult[], status: CheckStatus): number {
  return checks.filter(check => check.status === status).length;
}

function renderCheckRow(check: CheckResult): string {
  return `<tr>
    <td><span class="status status-${check.status}"><span class="dot"></span>${STATUS_LABEL[check.status]}</span></td>
    <td><span class="check-title">${escapeHtml(check.title)}</span><span class="check-detail">${escapeHtml(check.detail)}</span></td>
    <td class="points">${check.earned} / ${check.weight}</td>
    <td class="fix">${check.fix ? escapeHtml(check.fix) : '<span class="muted">No action needed.</span>'}</td>
  </tr>`;
}

